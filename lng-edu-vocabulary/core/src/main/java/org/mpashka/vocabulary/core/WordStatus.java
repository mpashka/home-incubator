package org.mpashka.vocabulary.core;

/**
 * Состояние обработки слова.
 *
 * <p>Значения перечислены в порядке возрастания готовности.
 */
public enum WordStatus {

    /** Перевода пока нет — слово стоит в очереди на разбор языковой моделью. */
    NO_TRANSLATION("нет перевода"),

    /** Слово перенесено из исходной базы, но связь с корнями ещё не описана. */
    IMPORTED("импортировано"),

    /** Слово разобрано языковой моделью, ждёт проверки человеком. */
    AWAITING_REVIEW("ждёт проверки"),

    /** Слово полностью обработано — есть в том числе блок о связи с корнями. */
    COMPLETE("полностью обработано");

    private final String title;

    WordStatus(String title) {
        this.title = title;
    }

    /** Название по-русски. */
    public String title() {
        return title;
    }
}
