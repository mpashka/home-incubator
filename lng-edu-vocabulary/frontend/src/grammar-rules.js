/** Правило по ключу и разновидности; `null`, если такого правила у нас нет. */
export function ruleFor (rule, ruleType) {
  if (rule !== 'noun-declension') return null
  const known = NOUN_RULES[ruleType]
  if (known) return { kind: 'known', ruleType, ...known }
  return { kind: 'absent', ruleType, title: 'Склонение существительных', reason: NOUN_RULES_ABSENT[ruleType] ?? NOUN_RULES_ABSENT.UNKNOWN }
}

/**
 * Разбор формы: основа и окончание по правилу.
 *
 * Считается по той же таблице окончаний, что показана рядом, — поэтому разбор не может
 * разойтись с правилом. Если форма правилу не отвечает (пришла из словаря), возвращает
 * `null`: выдавать словарную форму за выведенную нельзя.
 */
export function breakdown (rule, form) {
  if (rule?.kind !== 'known' || !form?.grammar) return null
  const [caseKey, number] = form.grammar.split('.')
  const cell = rule.endings[caseKey]?.[number === 'pl' ? 1 : 0]
  if (!cell) return null
  const ending = cell.split(' / ')[0].replace('*', '').replace('—', '').replace('-', '').trim()
  const value = form.form ?? ''
  if (!ending) return { stem: value, ending: '—' }
  if (!plain(value).endsWith(ending)) return null
  const [stem, tail] = splitTail(value, ending.length)
  return { stem, ending: tail }
}

/** Текст без комбинируемых знаков ударения. */
const plain = (text) => text.normalize('NFD').replace(/[̀-ͯ]/g, '')

/**
 * Отрезает от строки последние `count` букв, считая только сами буквы: знаки ударения
 * стоят отдельными код-точками и в счёт не идут, иначе окончание отрежется не по букве.
 */
function splitTail (text, count) {
  let index = text.length
  let letters = 0
  while (index > 0 && letters < count) {
    index--
    if (!/[̀-ͯ]/.test(text[index])) letters++
  }
  return [text.slice(0, index), text.slice(index)]
}
